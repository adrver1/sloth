"""Builds findings.md from findings.json (the review's findings, as written on 2026-11-13) and status.json (where each
one stands: which commit fixed it, or what it waits on). Edit status.json when a finding is fixed, then run:
    python docs/reviews/code-review-2026-11-13/build.py
A finding missing from status.json is open."""
import json, os
from collections import Counter

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = "https://github.com/adrver1/sloth/commit/"
F = json.load(open(os.path.join(HERE, "findings.json")))
S = json.load(open(os.path.join(HERE, "status.json")))
st = S["findings"]
RANK = {"critical": 0, "high": 1, "medium": 2, "low": 3}


def status(i):
    return st.get(i, {"status": "open", "commits": [], "note": ""})


def commits(s):
    return ", ".join(f"[{c}]({REPO}{c})" for c in s["commits"])


every = [x for a in F["areas"] for x in a["findings"]]
known = {x["id"] for x in every}
stray = sorted(set(st) - known)
if stray:
    raise SystemExit(f"status.json names findings that do not exist: {stray}")

out = ["# Canopy Camp code review: every finding, with its status", "",
       f"Generated by `build.py` from `findings.json` and `status.json`; do not edit by hand. Reviewed: {F['reviewed']}. "
       f"Statuses as of {S['as_of']}. Line numbers are on the reviewed commit. The ranked summary is in "
       "[code-review.md](code-review.md).", "",
       "Flags: **rebake** = needs a GPU bake to verify; **restructure** = changes how modules are split; "
       "**changes behaviour** = a visible or audible change (usually a bug fix). Effort: S under an hour, M a few hours, "
       "L a day or more.", "", "## Status", ""]
count = Counter(status(x["id"])["status"] for x in every)
out += ["| Status | Findings |", "|---|---|"] + [f"| {k} | {count[k]} |" for k in S["statuses"] if count[k]] + [f"| total | {len(every)} |", ""]
out += ["| Finding | Impact | Status | Commits | Note |", "|---|---|---|---|---|"]
for x in sorted(every, key=lambda x: (S["statuses"].index(status(x["id"])["status"]), RANK.get(x["impact"], 9), x["id"])):
    s = status(x["id"])
    if s["status"] == "open":
        continue
    out.append(f"| [{x['id']}](#{x['id']}) | {x['impact']} | {s['status']} | {commits(s)} | {s['note']} |")
out += ["", "Every finding not in this table is open.", ""]

for a in F["areas"]:
    out += [f"## {a['title']}", "", a["summary"][:1800], ""]
    for x in sorted(a["findings"], key=lambda x: (RANK.get(x["impact"], 9), x["id"])):
        s = status(x["id"])
        locs = "; ".join(f"`{l.get('file')}:{l.get('lines')}`" for l in x["locations"][:3] if isinstance(l, dict))
        fl = [k for k, on in (("rebake", x["needs_rebake"]), ("restructure", x["restructure"]),
                              ("changes behaviour", not x["behaviour_preserving"])) if on]
        line = f"**Status: {s['status']}**" + (f" in {commits(s)}" if s["commits"] else "") + (f". {s['note'][0].upper()}{s['note'][1:]}" if s["note"] else "")
        out += [f'<a id="{x["id"]}"></a>', f"### {x['id']} · {x['impact']} · {x['effort']} · {x['category']}",
                f"**{x['title']}**" + (f"  _({', '.join(fl)})_" if fl else ""), "", line, "",
                f"Where: {locs}", "", f"Why: {x['why']}", "", f"Fix: {x['fix']}", ""]
        if x.get("estimate_or_measured"):
            out += [f"Measured or estimate: {x['estimate_or_measured']}", ""]
open(os.path.join(HERE, "findings.md"), "w").write("\n".join(out))
print(f"findings.md: {len(every)} findings, " + ", ".join(f"{k} {count[k]}" for k in S["statuses"] if count[k]))
